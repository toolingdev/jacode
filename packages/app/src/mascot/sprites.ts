// Fork feature: the pixel characters that keep the user company while the model works.
//
// A sprite is 16x16 and mirror-symmetric, so only its left half is drawn here: each row is 8 characters, and the
// right half is that row reversed. `.` is empty, every other character names a palette color, and `e` marks an eye,
// which animations may close by drawing the `lid` color instead.

export type Sprite = {
  readonly id: string
  readonly name: string
  readonly palette: Readonly<Record<string, string>>
  /** The palette key eyes take while closed. */
  readonly lid: string
  /** Rows above this one are the head or hat, which some animations move on their own. */
  readonly neck: number
  readonly rows: readonly string[]
}

